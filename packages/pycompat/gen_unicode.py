"""Generates pycompat's Unicode tables from this Python's own str methods (so Rust answers as this Python does)."""
import sys
import unicodedata


def ranges(pred):
    out = []
    start = None
    for cp in range(0x110000):
        ok = pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def table(name, rs):
    body = ",\n".join("    (0x%X, 0x%X)" % r for r in rs)
    return "pub static %s: &[(u32, u32)] = &[\n%s,\n];\n" % (name, body)


decimal_zero = []
for cp in range(0x110000):
    c = chr(cp)
    if unicodedata.decimal(c, None) == 0:
        # the ten digits of one script are consecutive
        assert all(unicodedata.decimal(chr(cp + i), None) == i for i in range(10)), hex(cp)
        decimal_zero.append(cp)

out = ["//! Generated by gen_unicode.py from Python %s (Unicode %s): do not edit by hand.\n"
       % (sys.version.split()[0], unicodedata.unidata_version)]
out.append("/// The first code point (the zero) of each run of ten decimal digits (Python's int() and \\d).\n")
out.append("pub static DECIMAL_ZEROS: &[u32] = &[%s];\n" % ", ".join("0x%X" % z for z in decimal_zero))
out.append("/// str.isdigit()\n" + table("DIGIT", ranges(lambda c: c.isdigit())))
out.append("/// str.isspace()\n" + table("SPACE", ranges(lambda c: c.isspace())))
out.append("/// str.isprintable() (one character)\n" + table("PRINTABLE", ranges(lambda c: c.isprintable())))
out.append("/// \\w in a Python pattern on text: str.isalnum() or an underscore\n" + table("WORD", ranges(lambda c: c.isalnum() or c == "_")))
open(sys.argv[1], "w").write("\n".join(out))
